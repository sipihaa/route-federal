package ru.vladm.routefederal.data

// Соседний участок сети, по которому запрашиваются рейсы (в обе стороны).
// from/to — коды станций ("s...") или городов ("c..."), transportType — тип транспорта в API.
data class Link(
    val from: String,
    val to: String,
    val transportType: String,
)

