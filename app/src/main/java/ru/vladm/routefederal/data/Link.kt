package ru.vladm.routefederal.data

// Соседний участок сети, по которому запрашиваются рейсы (в обе стороны).
// from/to — коды станций ("s...") или городов ("c..."), transportType — тип транспорта в API.
data class Link(
    val from: String,
    val to: String,
    val transportType: String,
)

object Links {
    // Длинные поездки (например, Москва → Нижний Новгород) складываются из участков
    // одного и того же рейса, поэтому достаточно запрашивать соседние пары.
    val all = listOf(
        // Поезда дальнего следования
        Link("s2000001", "s2060340", "train"),    // Курский вокзал — Владимир
        Link("s9879173", "s2060340", "train"),    // Восточный вокзал — Владимир
        Link("s9879173", "s9612089", "train"),    // Восточный вокзал — Нижний Новгород
        Link("s2060340", "s9612089", "train"),    // Владимир — Нижний Новгород
        // Электрички
        Link("s2000001", "s9601539", "suburban"), // Курский вокзал — Орехово-Зуево
        Link("s9601539", "s9612144", "suburban"), // Орехово-Зуево — Петушки
        Link("s9612144", "s2060340", "suburban"), // Петушки — Владимир
        Link("s2000001", "s2060340", "suburban"), // Курский вокзал — Владимир
        // Автобусы: пары городов, ответ сужается до наших станций
        Link("c213", "c192", "bus"),              // Москва — Владимир
        Link("c192", "c23243", "bus"),            // Владимир — Нижний Новгород
        Link("c213", "c23243", "bus"),            // Москва — Нижний Новгород
        Link("c192", "c10671", "bus"),            // Владимир — Суздаль
    )
}
